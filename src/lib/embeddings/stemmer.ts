/**
 * Минималистичный стеммер русского языка по правилам Snowball.
 *
 * Назначение — нормализовать падежные/числовые/глагольные окончания
 * в запросе пользователя, чтобы regex-парсер фильтров видел корень
 * слова, а не словоформу.
 *
 *   «москве» → «москв»
 *   «двушке» → «двушк»
 *   «купить» → «куп»
 *   «новом доме» → «нов дом»
 *
 * Семантическому поиску (e5) стеммер не нужен — модель видит корни
 * сама. Это утилита **только для structured-parser**.
 *
 * Алгоритм — упрощённый Snowball (только адаптивно-частые окончания
 * для нашей домены: топонимы, единицы недвижимости). Без зависимостей.
 */

// Гласные русского алфавита.
const VOWELS = /[аеёиоуыэюя]/

// Окончания, отсортированные от длинных к коротким (важно для жадного
// matching). Покрывают: падежи существительных + прилагательных,
// инфинитивы и спрягаемые формы глаголов, прошедшее время.
const SUFFIXES: string[] = [
  // 4 letters
  'ивший', 'ившая', 'ившие', 'ивших', 'ившим', 'ившую',
  'ющий', 'ющая', 'ющее', 'ющие', 'ющих', 'ющим', 'ющую',
  'енной', 'енного', 'енные', 'ыми', 'ого', 'ому', 'ыми',
  // 3 letters
  'ого', 'ему', 'ого', 'ыми', 'ими', 'ого', 'ыми', 'ому',
  'ить', 'ать', 'ять', 'еть', 'оть', 'уть', 'ыть',
  'ешь', 'ишь', 'ешь',
  'ами', 'ями', 'ому', 'ему', 'ыми', 'ими',
  'ает', 'ает',
  // 2 letters
  'ой', 'ый', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие',
  'ом', 'ям', 'им', 'ям', 'ах', 'ях', 'ов', 'ев',
  'ть', 'ит', 'ат', 'ят', 'ет', 'ют', 'ил', 'ал', 'ел',
  'ло', 'ла', 'ли',
  'ам', 'ом', 'ем',
  // 1 letter (только если что-то после удаления остаётся длинное)
  'а', 'я', 'о', 'е', 'у', 'ю', 'ы', 'и', 'й', 'ь',
]

function stripSuffix(word: string): string {
  // Слишком короткие не трогаем — иначе «мск», «спб» исчезнут.
  if (word.length <= 4) return word

  for (const suf of SUFFIXES) {
    if (word.length - suf.length < 3) continue
    if (word.endsWith(suf)) {
      const stem = word.slice(0, -suf.length)
      // Убеждаемся что в корне есть гласная — иначе мы скорее всего
      // отрезали лишнее.
      if (VOWELS.test(stem)) return stem
    }
  }
  return word
}

/**
 * Возвращает stemmed-версию текста: каждое слово → корень.
 * Не-буквенные символы и цифры сохраняются как есть.
 */
export function stemRussianText(text: string): string {
  return text.replace(/[а-яё]+/giu, (word) => stripSuffix(word.toLowerCase()))
}
