interface Props {
  type: PropertyType
  /** Заголовок секции — можно переопределить. */
  heading?: string
}

/**
 * FAQ-секция с **видимыми** вопросами и JSON-LD рядом. <details>
 * нативный аккордеон — без JS, без CLS, без гидрации. JSON-LD
 * Google использует напрямую для «People also ask».
 */
export const PropertyFaq: React.FC<Props> = ({ type, heading }) => {
  const items = FAQ[type]
  if (!items?.length) return null

  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: items.map((item) => ({
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.a,
      },
    })),
  }

  return (
    <section className="bg-card rounded-md shadow-e1 p-6">
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
      />
      <h2 className="text-title-lg text-on-surface mb-4">
        {heading ?? 'Частые вопросы'}
      </h2>
      <div className="divide-y divide-border">
        {items.map((item, i) => (
          <details key={i} className="group py-3">
            <summary className="flex items-center justify-between gap-3 cursor-pointer text-body font-medium text-on-surface list-none">
              {item.q}
              <span
                aria-hidden="true"
                className="text-on-surface-variant transition-transform group-open:rotate-45 text-xl leading-none"
              >
                +
              </span>
            </summary>
            <p className="mt-2 text-body-sm text-on-surface-variant leading-relaxed">
              {item.a}
            </p>
          </details>
        ))}
      </div>
    </section>
  )
}
